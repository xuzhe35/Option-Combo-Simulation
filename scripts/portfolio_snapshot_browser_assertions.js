/* Real browser acceptance. Images/results stay in the supplied private output folder.
 * Usage: node scripts/portfolio_snapshot_browser_assertions.js --image <private.jpg> --output <private-dir>
 * Run the isolated local OCR service first. No broker endpoint is permitted.
 */
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const arg = key => process.argv.includes(key) ? process.argv[process.argv.indexOf(key) + 1] : undefined;
const input = path.resolve(arg('--image')), output = path.resolve(arg('--output'));
const golden = JSON.parse(fs.readFileSync(arg('--golden') || path.resolve(__dirname, '../tests/private_portfolio_snapshot/golden.json')));
const editedQuantity = String(Number(golden.positions[0].quantity) - 1);
const url = arg('--url')?.startsWith('http') ? arg('--url') : 'http://127.0.0.1:8798';
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(url).hostname));
assert.notEqual(new URL(url).port, '8765');
fs.mkdirSync(output, { recursive: true });
(async () => {
    const browser = await chromium.launch({ headless: true, channel: 'chrome' });
    try {
        const page = await browser.newPage({ viewport: { width: 1536, height: 1100 } });
        page.setDefaultTimeout(120000);
        const errors = [], forbidden = [];
        page.on('pageerror', e => errors.push(e.message));
        page.on('dialog', d => d.accept());
        await page.route('**/*', route => {
            const requested = new URL(route.request().url());
            if (requested.origin === new URL(url).origin || requested.protocol === 'blob:' || requested.protocol === 'data:') return route.continue();
            forbidden.push(requested.origin); return route.abort();
        });
        await page.goto(url + '/portfolio_snapshot.html');
        await page.waitForFunction(() => document.querySelector('#service-status').textContent.includes('已就绪'));
        assert.equal(await page.locator('#recognize').isDisabled(), true);
        await page.screenshot({ path: path.join(output, '01-empty.png'), fullPage: true });
        await page.locator('#image-file').setInputFiles({ name: 'invalid.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('not an image') });
        await page.waitForFunction(() => document.querySelector('#message').textContent.includes('实际的 PNG'));
        const bytes = [...fs.readFileSync(input)];
        await page.evaluate(({ bytes, name }) => {
            const dt = new DataTransfer(); dt.items.add(new File([new Uint8Array(bytes)], name, { type: 'image/jpeg' }));
            document.querySelector('#drop-zone').dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: dt }));
        }, { bytes, name: path.basename(input) });
        await page.waitForFunction(() => document.querySelector('#source-image').naturalWidth > 0 && !document.querySelector('#recognize').disabled);
        const recognized = page.waitForResponse(r => r.url().endsWith('/api/recognize'));
        await page.locator('#recognize').click();
        const recognitionResponse = await recognized;
        const raw = await recognitionResponse.json();
        assert.equal(recognitionResponse.ok(), true, raw.message || 'OCR request failed');
        fs.writeFileSync(path.join(output, 'raw-ocr.json'), JSON.stringify(raw));
        await page.waitForFunction(() => window.__portfolioSnapshot.getSnapshot().positions.length > 0, { timeout: 120000 });
        let snapshot = await page.evaluate(() => window.__portfolioSnapshot.getSnapshot());
        raw.quantityRereads = snapshot.recognition.originalQuantityRereads;
        raw.reviewRereads = snapshot.recognition.originalReviewRereads;
        fs.writeFileSync(path.join(output, 'raw-ocr.json'), JSON.stringify(raw));
        assert.equal(snapshot.positions.length, golden.positions.length); assert.equal(snapshot.cash.length, golden.cash.length); assert.equal(snapshot.sourceRows.length, golden.sourceRows);
        assert.equal(/\b(?:DU\d+|U\d{5,})\b/.test(JSON.stringify(snapshot)), false);
        assert.equal(snapshot.account.value, null); assert.equal(snapshot.asOf.date, null);
        assert.equal(snapshot.positions[0].quantity, golden.positions[0].quantity);
        assert.equal(snapshot.positions.at(-1).quantity, golden.positions.at(-1).quantity);
        const originalCashRaw = snapshot.cash[0].raw;
        assert.equal(snapshot.positions.every(p => p.reviewStatus === 'unreviewed'), true);
        const combo = snapshot.sourceRows.find(r => r.rowType === 'combo_summary');
        const firstComboLeg = snapshot.positions.find(p => p.sourceRowIds.includes(combo.combo.atomicLegRowIds[0]));
        assert.equal(combo.combo.atomicLegRowIds.length, 2);
        assert.equal(combo.combo.status, 'expanded_visible');
        assert.ok(snapshot.positions.every(p => !p.sourceRowIds.includes(combo.rowId)));
        assert.equal(snapshot.positions[11].instrument.symbol, 'NQ');
        assert.equal(snapshot.positions[11].instrument.tradingClass, 'NQ');
        assert.equal(snapshot.positions[11].fieldEvidence['instrument.symbol'].originalValue, 'NO');
        assert.equal(snapshot.positions[11].fieldEvidence['instrument.symbol'].corrections[0].passes.length, 2);
        assert.equal(await page.locator('#row-crop').isVisible(), true);
        await page.screenshot({ path: path.join(output, '02-recognized.png'), fullPage: true });
        await page.locator('[data-position-id="' + snapshot.positions[11].positionId + '"]').click();
        assert.equal(await page.locator('[data-field="instrument.symbol"]').inputValue(), 'NQ');
        assert.match(await page.locator('[data-field="instrument.symbol"]').locator('..').innerText(), /首次值 NO/);
        await page.screenshot({ path: path.join(output, '04-reread-evidence.png'), fullPage: true });
        await page.locator('#source-summary').click();
        const parentCard = page.locator('.source-evidence').filter({ hasText: '组合父行 · 不计持仓' });
        assert.equal(await parentCard.locator('.combo-leg').count(), 2);
        await parentCard.getByRole('button', { name: '查看原图', exact: true }).click();
        assert.equal(await page.locator('#editor').isVisible(), false);
        assert.match(await page.locator('#crop-title').innerText(), /组合/);
        await parentCard.locator('.combo-leg').first().click();
        assert.equal(await page.locator('[data-field="instrument.strike"]').inputValue(), firstComboLeg.instrument.strike);
        await page.locator('#source-summary').click();
        await page.locator('#row-filter').selectOption('problems');
        await page.locator('#confirm-all').click();
        await page.getByRole('button', { name: '确认以上字段并批量确认', exact: true }).click();
        await page.waitForFunction(()=>window.__portfolioSnapshot.getSnapshot().positions.every(p=>p.reviewStatus==='reviewed'));
        let bulk = await page.evaluate(() => window.__portfolioSnapshot.getSnapshot());
        assert.ok([...bulk.positions, ...bulk.cash].every(p => p.reviewStatus === 'reviewed'));
        assert.equal(bulk.review.status, 'reviewed');
        assert.equal(await page.locator('#confirm-all').isDisabled(), true);
        await page.locator('#row-filter').selectOption('all');
        await page.locator('#positions-body tr').first().click();
        assert.equal(await page.locator('[data-field="instrument.right"]').inputValue(), 'C');
        assert.match(await page.locator('[data-field="instrument.right"]').locator('..').innerText(), /按类型前缀/);
        await page.locator('#table-columns').selectOption('all');
        assert.ok(await page.locator('#positions-table th').count() > 10);
        await page.locator('#table-columns').selectOption('key');
        await page.locator('[data-field="quantity"]').fill(editedQuantity);
        await page.locator('[data-field="quantity"]').press('Tab');
        await page.waitForFunction(q => window.__portfolioSnapshot.getSnapshot().positions[0].quantity === q, editedQuantity);
        snapshot = await page.evaluate(() => window.__portfolioSnapshot.getSnapshot());
        assert.equal(snapshot.positions[0].reviewStatus, 'unreviewed');
        assert.ok(snapshot.positions.slice(1).every(p => p.reviewStatus === 'reviewed'));
        assert.equal(await page.locator('#confirm-all').isEnabled(), true);
        assert.equal(snapshot.positions[0].fieldEvidence.quantity.originalValue, golden.positions[0].quantity);
        await page.locator('#confirm-row').click();
        assert.equal(await page.evaluate(() => window.__portfolioSnapshot.getSnapshot().positions[0].reviewStatus), 'reviewed');
        await page.locator('[aria-label="现金金额"]').fill('12345.50');
        await page.locator('[aria-label="现金金额"]').press('Tab');
        assert.equal(await page.evaluate(() => window.__portfolioSnapshot.getSnapshot().cash[0].amount), '12345.5');
        assert.equal(await page.evaluate(() => window.__portfolioSnapshot.getSnapshot().cash[0].raw), originalCashRaw);
        await page.locator('[data-field="quantity"]').fill('12x');
        await page.locator('[data-field="quantity"]').press('Tab');
        assert.equal(await page.locator('#export-json').isDisabled(), true);
        await page.locator('#confirm-row').click();
        assert.match(await page.locator('#message').innerText(), /无效输入/);
        await page.locator('#confirm-all').click();
        assert.match(await page.locator('#message').innerText(), /无效输入/);
        assert.equal(await page.evaluate(() => window.__portfolioSnapshot.getSnapshot().cash[0].reviewStatus), 'unreviewed');
        await page.locator('[data-field="quantity"]').fill(editedQuantity);
        await page.locator('[data-field="quantity"]').press('Tab');
        await page.locator('#account').fill('U0000000'); await page.locator('#account').press('Tab');
        await page.locator('#asof').fill('2030-01-02'); await page.locator('#asof').press('Tab');
        await page.locator('#row-filter').selectOption('pending');
        assert.equal(await page.locator('#positions-body tr[data-position-id]').count(), 0);
        await page.locator('#row-filter').selectOption('all');
        await page.locator('#tab-portfolio').click(); assert.equal(await page.locator('.source-panel').isVisible(), false);
        await page.locator('#tab-review').click();
        const downloaded = page.waitForEvent('download'); await page.locator('#export-json').click();
        const download = await downloaded, target = path.join(output, 'exported-snapshot.json'); await download.saveAs(target);
        const exported = JSON.parse(fs.readFileSync(target));
        assert.equal(exported.account.value, 'U0000000'); assert.equal(exported.positions[0].quantity, editedQuantity);
        assert.equal(exported.cash[0].amount, '12345.5');
        await page.locator('#json-file').setInputFiles(target);
        await page.waitForFunction(() => document.querySelector('#message').textContent.includes('JSON 已导入'));
        assert.equal(await page.evaluate(() => window.__portfolioSnapshot.getSnapshot().positions[0].quantity), editedQuantity);
        await page.locator('#image-file').setInputFiles(input);
        await page.waitForFunction(() => document.querySelector('#message').textContent.includes('相同原图'));
        assert.equal(await page.evaluate(() => window.__portfolioSnapshot.getSnapshot().positions[0].quantity), editedQuantity);
        const copySafe = await page.evaluate(() => { const s = window.__portfolioSnapshot.getSnapshot(); s.positions[0].quantity = '999'; return window.__portfolioSnapshot.getSnapshot().positions[0].quantity; });
        assert.equal(copySafe, editedQuantity);
        // A delayed/aborted recognition must not overwrite the manually corrected table.
        let unblock;
        const wait = new Promise(resolve => { unblock = resolve; });
        await page.route('**/api/recognize', async route => { await wait; try { await route.fulfill({ json: raw }); } catch (_) { /* Browser canceled it. */ } });
        await page.locator('#recognize').click(); await page.locator('#cancel-ocr').click(); unblock();
        await page.waitForFunction(() => document.querySelector('#recognize').disabled === false);
        assert.equal(await page.evaluate(() => window.__portfolioSnapshot.getSnapshot().positions[0].quantity), editedQuantity);
        await page.setViewportSize({ width: 390, height: 844 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        await page.screenshot({ path: path.join(output, '03-mobile.png'), fullPage: true });
        // Structural UI checks use labelled synthetic OCR fixtures, not accuracy measurements.
        await page.setViewportSize({ width: 1536, height: 1100 });
        await page.unroute('**/api/recognize');
        const fixtureImage = require('../tests/portfolio_snapshot_structure.test').image;
        const fixtures = [fixtureImage([{desc:'XYZ Iron Condor',qty:'99'}]), fixtureImage([
            {desc:'XYZ UnseenPack',qty:'99'}, {desc:"XYZ Oct21'30 45 PUT",qty:'1',indent:.112},
            {desc:"XYZ Oct21'30 50 PUT",qty:'-2',indent:.112}, {desc:"XYZ Nov21'30 55 CALL",qty:'1',indent:.112},
            {desc:'PEER',qty:'7'}])].map(r => ({...r, sourceHash:raw.sourceHash, width:raw.width,height:raw.height}));
        await page.route('**/api/recognize', route => route.fulfill({json:fixtures.shift()}));
        await page.locator('#recognize').click();
        await page.getByRole('button',{name:'采用新结果',exact:true}).click();
        await page.waitForFunction(()=>window.__portfolioSnapshot.getSnapshot().sourceRows[0]?.combo?.status==='collapsed');
        assert.equal(await page.evaluate(()=>window.__portfolioSnapshot.getSnapshot().positions.length),0);
        assert.equal(await page.locator('#structure-warning').isVisible(),true);
        assert.match(await page.locator('#structure-warning').innerText(),/未展开/);
        await page.locator('#recognize').click();
        await page.getByRole('button',{name:'采用新结果',exact:true}).click();
        await page.waitForFunction(()=>window.__portfolioSnapshot.getSnapshot().positions.length===4);
        assert.equal(await page.locator('#structure-warning').isVisible(),false);
        assert.equal(await page.evaluate(()=>window.__portfolioSnapshot.getSnapshot().sourceRows.at(-1).parentRowId),null);
        if (!await page.locator('#source-rows').isVisible()) await page.locator('#source-summary').click();
        assert.equal(await page.locator('.source-evidence .combo-leg').count(),3);
        const privateResponse = await page.request.get(url + '/Portfolio%20SC/20261020.jpg'); assert.equal(privateResponse.status(), 404);
        assert.deepEqual(errors, []); assert.deepEqual(forbidden, []);
        console.log('Browser acceptance passed: real OCR and crop evidence, 15 positions/1 cash, combo leg navigation, collapsed/unknown strategy UI, edits, JSON round trip, cancellation, mobile layout, private assets.');
    } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
